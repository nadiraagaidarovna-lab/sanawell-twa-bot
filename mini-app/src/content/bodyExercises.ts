export interface ExerciseItem {
  title: string;
  /** Абзацы разделены пустой строкой (\n\n). Без описания и шагов упражнение — просто строка. */
  description?: string;
  /** Пояснение «почему это важно» — отдельным курсивным абзацем после описания. */
  why?: string;
  /** Подпись над списком steps, например «Как делать:». */
  stepsLabel?: string;
  steps?: string[];
  /** Завершающая строка после шагов (подходы/повторения и т.п.). */
  footer?: string;
  /** Врезка-предостережение внутри упражнения (выделяется визуально). */
  note?: string;
}

export interface ExerciseSection {
  title: string;
  intro?: string;
  /** Врезки-предостережения раздела — выделяются визуально и идут до списка упражнений. */
  notes?: string[];
  /** Подпись над списком упражнений. */
  itemsLabel?: string;
  /** Завершающий абзац раздела после упражнений. */
  outro?: string;
  items: ExerciseItem[];
}

