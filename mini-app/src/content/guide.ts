/** Все карточки Гида: Тема 0 (по пути менопаузы) первой, затем Тема «Суставы и плечи». */
export function getGuideCards(menopausePath: 'natural' | 'surgical' | 'oncological' | null): GuideCard[] {
  return [...getTheme0Cards(menopausePath), ...JOINTS_SHOULDERS_CARDS];
}

export function getTheme0Cards(menopausePath: 'natural' | 'surgical' | 'oncological' | null): GuideCard[] {
  if (menopausePath === 'surgical' || menopausePath === 'oncological') {
    return [
      SURGICAL_ONCOLOGICAL_INTRO,
      BASE_CARDS[2], // Постменопауза — без изменений
      withRiskAddendum(BASE_CARDS[3]), // Мозг
      withRiskAddendum(BASE_CARDS[4]), // Кости
      withRiskAddendum(BASE_CARDS[5]), // Саркопения
      withRiskAddendum(BASE_CARDS[6]), // Сердце и сосуды
      menopausePath === 'oncological' ? ONCOLOGICAL_CLOSING : BASE_CARDS[7],
    ];
  }
  // natural, а также null/неизвестно — то же техническое решение по умолчанию,
  // что уже принято для анкеты ("затрудняюсь ответить" -> natural).
  return BASE_CARDS;
}
