// safety.js — детектор маркеров риска в свободном тексте пользователя.
// ВАЖНО: это простая проверка по ключевым фразам для MVP, а не клиническая
// оценка риска. Задача — не пропустить очевидный сигнал и мягко перенаправить
// к специалистам/линиям доверия, а не пытаться "разговорить" или утешить самим ботом.
//
// Юридическая граница продукта: тяжёлая депрессия и суицидальные мысли —
// строго вне рамок приложения (см. ТЗ, раздел 2 "Границы продукта").

const RISK_PATTERNS = [
  // русские маркеры — суицидальные
  /не хочу жить/i,
  /покончить с собой/i,
  /суицид/i,
  /самоубийств/i,
  /лучше бы (я )?не было/i,
  /никому не нужна/i,
  /нет смысла жить/i,
  // русские маркеры — тяжёлая депрессия / самоповреждение
  /причинить себе (боль|вред)/i,
  /хочу умереть/i,
  /навредить себе/i,

  // Казахские маркеры проверяются ОДНОВРЕМЕННО с русскими и не зависят от того,
  // какой язык интерфейса выбран сейчас (ТЗ, Модуль 5.4). Черновой набор для MVP —
  // требует вычитки и расширения носителем языка / партнёром-психологом до реальных пользователей.
  /өмір сүргім келмейді/i,
  /өзіме қол жұмса/i,
  /суицид/i,
  /өзімді өлтір/i,
  /өлгім келеді/i,
  /ешкімге керек емеспін/i,
  /өмірдің мәні жоқ/i,
  /өзіме зиян келтір/i,
];

// В Казахстане нет единого федерального номера доверия, поэтому даём
// сочетание республиканской линии и общего экстренного номера.
// Надире стоит проверить и актуализировать этот блок с юристом/психологом-партнёром.
const SAFETY_RESOURCES = {
  message:
    'Похоже, вам сейчас очень тяжело — и это важно не оставлять без поддержки специалиста. ' +
    'Этот бот не предназначен для помощи в таких ситуациях, но помощь есть:',
  resources: [
    { label: 'Телефон доверия (Казахстан, бесплатно, 24/7)', value: '150' },
    { label: 'Единый номер экстренных служб', value: '112' },
    { label: 'Найти психотерапевта или психиатра очно', value: 'обратитесь в поликлинику по месту жительства' },
  ],
};

function detectRiskTrigger(text) {
  if (!text || typeof text !== 'string') return null;
  const match = RISK_PATTERNS.find((pattern) => pattern.test(text));
  return match ? match.source : null;
}

function getSafetyResources() {
  return SAFETY_RESOURCES;
}

module.exports = { detectRiskTrigger, getSafetyResources };
